"""Vector storage and retrieval against PostgreSQL + pgvector.

Two retrieval strategies are implemented:

``exact``
    A sequential scan over the training pool with the pgvector distance
    function applied to every candidate row. This is the ground truth used
    for recall computation and the accuracy baseline.

``hnsw``
    An index scan over a Hierarchical Navigable Small World index. The
    ``ef_search`` GUC controls the search-effort and directly drives the
    recall / latency trade-off studied in the project.

Both strategies share the same SQL shape so that the *only* difference
between a baseline run and an approximate run is the presence of the index
and the planner's choice of access path.

Each dataset owns a pair of tables (``fv_<id>`` / ``tv_<id>``) with a
dimensionally-typed ``vector(dim)`` column, which is what pgvector requires
for a usable HNSW index.
"""

from __future__ import annotations

import json
import logging
import time
from dataclasses import dataclass
from typing import Sequence

from psycopg import sql

from app.core.database import connection
from app.services.metrics import DistanceMetric

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Table naming
# ---------------------------------------------------------------------------
def train_table(dataset_id: int) -> str:
    return f"fv_{int(dataset_id)}"


def test_table(dataset_id: int) -> str:
    return f"tv_{int(dataset_id)}"


def index_name(dataset_id: int) -> str:
    return f"fv_{int(dataset_id)}_embedding_hnsw_idx"


# ---------------------------------------------------------------------------
# Table lifecycle
# ---------------------------------------------------------------------------
def create_dataset_tables(dataset_id: int, dimension: int) -> None:
    """Create the train/test tables for a dataset with a typed vector column."""
    dim = int(dimension)
    with connection() as conn:
        with conn.cursor() as cur:
            for table in (train_table(dataset_id), test_table(dataset_id)):
                cur.execute(sql.SQL("DROP TABLE IF EXISTS {t} CASCADE").format(
                    t=sql.Identifier(table)
                ))
                cur.execute(
                    sql.SQL(
                        "CREATE TABLE {t} ("
                        "  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        "  row_index   INTEGER NOT NULL,"
                        "  label       SMALLINT NOT NULL,"
                        "  embedding   vector({dim}) NOT NULL"
                        ")"
                    ).format(t=sql.Identifier(table), dim=sql.Literal(dim))
                )
                cur.execute(
                    sql.SQL("CREATE INDEX {i} ON {t} (row_index)").format(
                        i=sql.Identifier(f"{table}_row_idx"), t=sql.Identifier(table)
                    )
                )
    logger.info("Created vector tables for dataset %s (dim=%s)", dataset_id, dim)


def drop_dataset_tables(dataset_id: int) -> None:
    with connection() as conn:
        with conn.cursor() as cur:
            for table in (train_table(dataset_id), test_table(dataset_id)):
                cur.execute(sql.SQL("DROP TABLE IF EXISTS {t} CASCADE").format(
                    t=sql.Identifier(table)
                ))


# ---------------------------------------------------------------------------
# Ingestion
# ---------------------------------------------------------------------------
def insert_vectors(
    dataset_id: int,
    which: str,
    embeddings: Sequence[str],
    labels: Sequence[int],
    row_indices: Sequence[int],
) -> int:
    """Bulk insert feature vectors using COPY for throughput."""
    table = train_table(dataset_id) if which == "train" else test_table(dataset_id)

    with connection() as conn:
        with conn.cursor() as cur:
            with cur.copy(
                sql.SQL(
                    "COPY {table} (row_index, label, embedding) FROM STDIN"
                ).format(table=sql.Identifier(table))
            ) as copy:
                for emb, lab, idx in zip(embeddings, labels, row_indices):
                    copy.write_row((int(idx), int(lab), emb))
    logger.info("Inserted %s rows into %s", len(labels), table)
    return len(labels)


def count_vectors(dataset_id: int, which: str = "train") -> int:
    table = train_table(dataset_id) if which == "train" else test_table(dataset_id)
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                sql.SQL("SELECT count(*) AS c FROM {t}").format(t=sql.Identifier(table))
            )
            row = cur.fetchone()
            return int(row["c"]) if row else 0


def load_test_vectors(dataset_id: int, limit: int | None) -> list[tuple[int, int, str]]:
    """Return ``(id, label, embedding_text)`` triples for the query pool."""
    table = test_table(dataset_id)
    limit_clause = sql.SQL(" LIMIT {n}").format(n=sql.Literal(limit)) if limit else sql.SQL("")
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                sql.SQL(
                    "SELECT id, label, embedding::text AS embedding FROM {t} ORDER BY id{l}"
                ).format(t=sql.Identifier(table), l=limit_clause)
            )
            return [(int(r["id"]), int(r["label"]), r["embedding"]) for r in cur.fetchall()]


