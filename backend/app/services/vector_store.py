# Index management
# ---------------------------------------------------------------------------
def drop_hnsw_index(dataset_id: int) -> None:
    """Remove the HNSW index for a dataset (used before exact-only runs)."""
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("DROP INDEX IF EXISTS {i}").format(
                i=sql.Identifier(index_name(dataset_id))
            ))


@dataclass
class IndexInfo:
    """What actually happened to the HNSW index during this run.

    ``created`` distinguishes a fresh ``CREATE INDEX`` from a reuse of an
    index that was built by an earlier experiment. Only a fresh build has a
    meaningful ``build_ms``; reporting a reused index's historical build time
    as though it were paid again on every ``ef_search`` configuration would
    misstate the cost of an index sweep.
    """

    created: bool
    build_ms: float | None
    m: int
    ef_construction: int
    size_bytes: int | None
    distance_metric: str


def ensure_hnsw_index(
    dataset_id: int,
    metric: DistanceMetric,
    m: int = 16,
    ef_construction: int = 64,
    force: bool = False,
) -> IndexInfo:
    """Build the HNSW index, or reuse an equivalent one.

    The returned :class:`IndexInfo` records whether a build really happened,
    which parameters the live index has, and its physical size. This is the
    authoritative source for the persisted index metadata — the defaults in
    Python are not evidence of what PostgreSQL actually built.
    """
    existing = get_hnsw_index(dataset_id)
    if (
        not force
        and existing is not None
        and existing["distance_metric"] == metric.value
        and int(existing["m"]) == int(m)
        and int(existing["ef_construction"]) == int(ef_construction)
        and hnsw_index_exists(dataset_id)
    ):
        logger.info("Reusing existing HNSW index for dataset %s", dataset_id)
        return IndexInfo(
            created=False,
            build_ms=float(existing["build_ms"]) if existing["build_ms"] is not None else None,
            m=int(existing["m"]),
            ef_construction=int(existing["ef_construction"]),
            size_bytes=index_size_bytes(dataset_id),
            distance_metric=str(existing["distance_metric"]),
        )

    elapsed = _build_hnsw_index(dataset_id, metric, m, ef_construction)
    record = get_hnsw_index(dataset_id) or {}
    return IndexInfo(
        created=True,
        build_ms=elapsed,
        m=int(record.get("m", m)),
        ef_construction=int(record.get("ef_construction", ef_construction)),
        size_bytes=index_size_bytes(dataset_id),
        distance_metric=metric.value,
    )


def create_hnsw_index(
    dataset_id: int,
    metric: DistanceMetric,
    m: int = 16,
    ef_construction: int = 64,
    force: bool = False,
) -> float:
    """Backward-compatible wrapper returning the build time in milliseconds.

    Returns ``0.0`` when the index was reused, because no build happened.
    Call :func:`ensure_hnsw_index` when the created/reused distinction
    matters.
    """
    info = ensure_hnsw_index(dataset_id, metric, m=m, ef_construction=ef_construction, force=force)
    return float(info.build_ms or 0.0)


def _build_hnsw_index(
    dataset_id: int,
    metric: DistanceMetric,
    m: int,
    ef_construction: int,
) -> float:
    """Run ``CREATE INDEX`` and record the measured build in the registry."""
    ops = {
        DistanceMetric.L2: "vector_l2_ops",
        DistanceMetric.COSINE: "vector_cosine_ops",
        DistanceMetric.L1: "vector_l1_ops",
    }[metric]

    drop_hnsw_index(dataset_id)
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute("SET maintenance_work_mem = '512MB'")
            start = time.perf_counter()
            cur.execute(
                sql.SQL(
                    "CREATE INDEX {idx} ON {t} USING hnsw (embedding {ops}) "
                    "WITH (m = {m}, ef_construction = {efc})"
                ).format(
                    idx=sql.Identifier(index_name(dataset_id)),
                    t=sql.Identifier(train_table(dataset_id)),
                    ops=sql.SQL(ops),
                    m=sql.Literal(m),
                    efc=sql.Literal(ef_construction),
                )
            )
            elapsed = (time.perf_counter() - start) * 1000
            size_bytes = index_size_bytes(dataset_id)
            cur.execute(
                sql.SQL(
                    "INSERT INTO hnsw_indexes "
                    "(dataset_id, distance_metric, m, ef_construction, build_ms, size_bytes, built_at) "
                    "VALUES (%s, %s, %s, %s, %s, %s, now()) "
                    "ON CONFLICT (dataset_id) DO UPDATE SET "
                    "distance_metric = EXCLUDED.distance_metric, "
                    "m = EXCLUDED.m, "
                    "ef_construction = EXCLUDED.ef_construction, "
                    "build_ms = EXCLUDED.build_ms, "
                    "size_bytes = EXCLUDED.size_bytes, "
                    "built_at = now()"
                ),
                (
                    dataset_id,
                    metric.value,
                    int(m),
                    int(ef_construction),
                    elapsed,
                    size_bytes,
                ),
            )
    logger.info(
        "HNSW index built in %.1f ms (m=%s, ef_construction=%s, size=%s bytes)",
        elapsed,
        m,
        ef_construction,
        size_bytes,
    )
    return elapsed


def get_hnsw_index(dataset_id: int) -> dict | None:
    """Return the recorded HNSW index parameters for a dataset, if any."""
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT * FROM hnsw_indexes WHERE dataset_id = %s", (dataset_id,)
            )
            return cur.fetchone()


def hnsw_index_exists(dataset_id: int) -> bool:
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT 1 AS present FROM pg_indexes "
                "WHERE tablename = %s AND indexname = %s",
                (train_table(dataset_id), index_name(dataset_id)),
            )
            return cur.fetchone() is not None


def analyze(dataset_id: int) -> None:
    """Refresh planner statistics so it can pick the right access path."""
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("ANALYZE {t}").format(t=sql.Identifier(train_table(dataset_id))))
            cur.execute(sql.SQL("ANALYZE {t}").format(t=sql.Identifier(test_table(dataset_id))))


def index_size_bytes(dataset_id: int) -> int | None:
    """The on-disk size of the HNSW index, in bytes.

    Returns ``None`` when no index exists. The size is read from
    ``pg_relation_size`` so that it reflects the physical footprint rather
    than an estimate.
    """
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT pg_relation_size(%s) AS size", (index_name(dataset_id),)
            )
            row = cur.fetchone()
            if row is None or row["size"] is None:
                return None
            return int(row["size"])


def plan_uses_index_scan(plan_text: str, index_name_: str | None = None) -> bool:
    """Detect whether the planner chose an HNSW index scan.

    When ``index_name_`` is given, the plan must reference that specific
    index. This matters because a btree index scan would otherwise satisfy
    the generic check and produce a false positive.
    """
    lowered = plan_text.lower()
    if "index scan" not in lowered:
        return False
    if index_name_ is not None:
        return index_name_.lower() in lowered
    return "hnsw" in lowered or "index searches" in lowered


def plan_uses_sequential_scan(plan_text: str) -> bool:
    """Detect whether the planner fell back to an exhaustive sequential scan."""
    lowered = plan_text.lower()
    return "seq scan" in lowered


# ---------------------------------------------------------------------------
# Retrieval
# ---------------------------------------------------------------------------
@dataclass
class Neighbour:
    row_id: int
    label: int
    distance: float


@dataclass
class RetrievalResult:
    neighbours: list[Neighbour]
    latency_ms: float
    used_index_scan: bool
    plan: str
    used_sequential_scan: bool = False
    applied_ef_search: int | None = None


def _distance_expr(metric: DistanceMetric, use_operator: bool) -> sql.Composable:
    """Distance expression for the metric.

    The *operator* form (``embedding <-> %s``) is what pgvector's HNSW index
    can satisfy; the *function* form (``l2_distance(...)``) always forces a
    full sequential scan and therefore serves as the exact baseline.
    """
    if use_operator:
        return sql.SQL("embedding {} %s").format(sql.SQL(metric.operator))
    return sql.SQL("{} (embedding, %s::vector)").format(sql.SQL(metric.function))


def _query_sql(
    dataset_id: int, metric: DistanceMetric, k: int, use_operator: bool
) -> sql.Composed:
    dist = _distance_expr(metric, use_operator)
    return sql.SQL(
        "SELECT id, label, {dist} AS distance "
        "FROM {t} "
        "ORDER BY {dist} "
        "LIMIT {k}"
    ).format(dist=dist, t=sql.Identifier(train_table(dataset_id)), k=sql.Literal(k))


def _explain_sql(
    dataset_id: int, metric: DistanceMetric, k: int, use_operator: bool
) -> sql.Composed:
    dist = _distance_expr(metric, use_operator)
    return sql.SQL(
        "EXPLAIN (ANALYZE, BUFFERS, FORMAT TEXT) "
        "SELECT id, label, {dist} AS distance "
        "FROM {t} "
        "ORDER BY {dist} "
        "LIMIT {k}"
    ).format(dist=dist, t=sql.Identifier(train_table(dataset_id)), k=sql.Literal(k))


def retrieve(
    query_vector: str,
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    method: str = "exact",
    ef_search: int | None = None,
    use_operator: bool = True,
    warmup: bool = True,
    verify_plan: bool = True,
) -> RetrievalResult:
    """Run a single nearest-neighbour query and time it.

    ``method='exact'`` uses the distance *function* form, which can never be
    satisfied by an index and therefore guarantees an exhaustive scan.
    ``method='hnsw'`` uses the *operator* form so the planner can choose an
    HNSW index scan.

    The search-effort parameter is set at *session* level rather than with
    ``SET LOCAL``, because the connection pool runs in autocommit mode where
    ``SET LOCAL`` is silently discarded. The value is read back from the
    server to confirm that it was actually applied, and it is restored in a
    ``finally`` block so that a pooled connection never leaks the setting
    into a later request.
    """
    use_op = method == "hnsw" and use_operator
    applied_ef: int | None = None

    with connection() as conn:
        with conn.cursor() as cur:
            if ef_search is not None:
                cur.execute(f"SET hnsw.ef_search = {int(ef_search)}")
                # Confirm the server actually took the value.
                cur.execute("SHOW hnsw.ef_search")
                row = cur.fetchone()
                applied_ef = int(row["hnsw.ef_search"]) if row else None
            try:
                stmt = _query_sql(dataset_id, metric, k, use_op)
                params: tuple = (query_vector, query_vector)

                # Warm-up run so that the measured latency is not dominated by
                # first-call planning and buffer-cache population.
                if warmup:
                    cur.execute(stmt, params)
                    cur.fetchall()

                start = time.perf_counter()
                cur.execute(stmt, params)
                rows = cur.fetchall()
                elapsed_ms = (time.perf_counter() - start) * 1000

                plan = ""
                used_index = False
                used_seq_scan = False
                if verify_plan:
                    cur.execute(_explain_sql(dataset_id, metric, k, use_op), params)
                    plan = "\n".join(r["QUERY PLAN"] for r in cur.fetchall())
                    used_index = plan_uses_index_scan(plan, index_name(dataset_id))
                    used_seq_scan = plan_uses_sequential_scan(plan)
            finally:
                if ef_search is not None:
                    cur.execute("RESET hnsw.ef_search")

    neighbours = [
        Neighbour(
            row_id=int(r["id"]),
            label=int(r["label"]),
            distance=float(r["distance"]),
        )
        for r in rows
    ]
    return RetrievalResult(
        neighbours=neighbours,
        latency_ms=elapsed_ms,
        used_index_scan=used_index,
        plan=plan,
        used_sequential_scan=used_seq_scan,
        applied_ef_search=applied_ef,
    )


@dataclass
class BatchResult:
    """The outcome of a repeated timed query sweep.

    ``repetition_results[r]`` holds one :class:`RetrievalResult` per query
    for repetition ``r``, in the same query order every time. Keeping every
    repetition's neighbour sets — rather than only the last one — is what
    allows classification metrics to be computed *per repetition* instead of
    being inferred from a single aggregate.

    ``repetition_latencies[r]`` holds the measured latency of each query in
    that repetition. The warm-up query runs before the first measurement and
    is never stored, so ``sample_count == repetitions * unique_query_count``
    exactly.
    """

    repetition_results: list[list[RetrievalResult]]
    repetition_latencies: list[list[float]]
    repetitions: int
    warmup_queries: int
    plan: str = ""
    used_index_scan: bool = False
    used_sequential_scan: bool = False
    applied_ef_search: int | None = None

    @property
    def results(self) -> list[RetrievalResult]:
        """Neighbour sets from the final repetition."""
        return self.repetition_results[-1]

    @property
    def latencies(self) -> list[float]:
        """Every measured latency sample, flattened across repetitions."""
        return [ms for batch in self.repetition_latencies for ms in batch]

    @property
    def unique_query_count(self) -> int:
        return len(self.repetition_results[0]) if self.repetition_results else 0

    @property
    def sample_count(self) -> int:
        return sum(len(batch) for batch in self.repetition_latencies)


def retrieve_batch(
    query_vectors: Sequence[str],
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    method: str = "exact",
    ef_search: int | None = None,
    repetitions: int = 1,
    verify_plan: bool = True,
) -> BatchResult:
    """Run the query set ``repetitions`` times over the same vectors.

    Each repetition is a complete timed pass over the whole query set. The
    query order is identical in every repetition: the repetitions are
    intended to expose run-to-run variability in timing and index traversal,
    not to resample the query set. They are therefore **not** independent
    observations of a population.

    The execution plan is verified once, on the first query of the first
    repetition, and the captured plan/flags are reported for the whole batch.
    Running ``EXPLAIN (ANALYZE)`` for every query would double the work and
    interleave planner execution with the timed measurements.

    One warm-up query is executed before the first measurement and discarded.
    """
    if repetitions < 1:
        raise ValueError(f"repetitions must be at least 1 (got {repetitions})")

    repetition_results: list[list[RetrievalResult]] = []
    repetition_latencies: list[list[float]] = []
    plan = ""
    used_index = False
    used_seq = False
    applied_ef: int | None = None

    for repetition in range(repetitions):
        current: list[RetrievalResult] = []
        latencies: list[float] = []
        for i, vec in enumerate(query_vectors):
            first = repetition == 0 and i == 0
            result = retrieve(
                query_vector=vec,
                k=k,
                metric=metric,
                dataset_id=dataset_id,
                method=method,
                ef_search=ef_search,
                # The warm-up must precede the first timed query only.
                warmup=first,
                verify_plan=verify_plan and first,
            )
            current.append(result)
            latencies.append(result.latency_ms)
            if first:
                plan = result.plan
                used_index = result.used_index_scan
                used_seq = result.used_sequential_scan
                applied_ef = result.applied_ef_search
        repetition_results.append(current)
        repetition_latencies.append(latencies)

    return BatchResult(
        repetition_results=repetition_results,
        repetition_latencies=repetition_latencies,
        repetitions=repetitions,
        warmup_queries=1 if query_vectors else 0,
        plan=plan,
        used_index_scan=used_index,
        used_sequential_scan=used_seq,
        applied_ef_search=applied_ef,
    )


@dataclass
class TieTolerance:
    """Floating-point tolerance for "equally distant" in tie-aware recall.

    Two rows are treated as equally valid neighbours when

    ``distance <= boundary * (1 + relative) + absolute``

    where ``boundary`` is the exact K-th neighbour distance. An exact tie
    between duplicate feature vectors produces bit-identical distance values,
    so the tolerance only has to absorb float4/float8 representation error;
    it must be far smaller than the spacing between genuinely distinct
    distances.
    """

    relative: float = 1e-6
    absolute: float = 1e-6


@dataclass
class GroundTruth:
    """Exact neighbours plus the tie-tolerant candidate set for one query."""

    ids: list[int]
    distances: list[float]
    boundary: float
    candidate_ids: list[int]
    candidate_labels: dict[int, int]

    @property
    def is_tied(self) -> bool:
        return len(self.candidate_ids) > len(self.ids)


def _ground_truth_sql(
    dataset_id: int, metric: DistanceMetric, k: int
) -> sql.Composed:
    """Exhaustive top-k plus every row tied at the K-th distance.

    ``ORDER BY distance, id`` makes the conventional reference deterministic:
    without the id tiebreak the K-th boundary row is chosen arbitrarily by
    the executor, which would make conventional Recall@K irreproducible.
    """
    dist = _distance_expr(metric, use_operator=False)
    return sql.SQL(
        "WITH scored AS ("
        "  SELECT id, label, {dist} AS distance FROM {t}"
        "), boundary AS ("
        "  SELECT COALESCE("
        "    (SELECT distance FROM scored ORDER BY distance LIMIT 1 OFFSET {off}),"
        "    (SELECT max(distance) FROM scored)"
        "  ) AS b"
        ")"
        " SELECT id, label, distance FROM scored"
        " WHERE distance <= (SELECT b FROM boundary) * (1 + %s) + %s"
        " ORDER BY distance, id"
    ).format(dist=dist, t=sql.Identifier(train_table(dataset_id)), off=sql.Literal(k - 1))


def ground_truth_candidates(
    query_vectors: Sequence[str],
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    tolerance: TieTolerance | None = None,
) -> list[GroundTruth]:
    """Reference neighbour set for every query, tie-tolerant.

    Returns one :class:`GroundTruth` per query containing the exact top-k
    ids/distances (deterministic by ``(distance, id)``), the K-th boundary
    distance, and every training id within the tie tolerance of that
    boundary.
    """
    tol = tolerance or TieTolerance()
    stmt = _ground_truth_sql(dataset_id, metric, k)
    out: list[GroundTruth] = []

    with connection() as conn:
        with conn.cursor() as cur:
            for vec in query_vectors:
                cur.execute(stmt, (vec, tol.relative, tol.absolute))
                rows = cur.fetchall()
                ids = [int(r["id"]) for r in rows]
                distances = [float(r["distance"]) for r in rows]
                if not ids:
                    out.append(GroundTruth([], [], 0.0, [], {}))
                    continue
                boundary = distances[k - 1] if len(distances) >= k else distances[-1]
                out.append(
                    GroundTruth(
                        ids=ids[:k],
                        distances=distances[:k],
                        boundary=boundary,
                        candidate_ids=ids,
                        candidate_labels={
                            int(r["id"]): int(r["label"]) for r in rows
                        },
                    )
                )
    return out


def ground_truth_ids(
    query_vectors: Sequence[str],
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
) -> list[list[int]]:
    """Exact top-k neighbour ids, used as the conventional recall reference."""
    return [
        gt.ids
        for gt in ground_truth_candidates(query_vectors, k, metric, dataset_id)
    ]


def explain_plan(
    query_vector: str,
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    ef_search: int | None = None,
) -> str:
    """Return the EXPLAIN output for the retrieval query."""
    with connection() as conn:
        with conn.cursor() as cur:
            if ef_search is not None:
                cur.execute(f"SET hnsw.ef_search = {int(ef_search)}")
            try:
                cur.execute(
                    _explain_sql(dataset_id, metric, k, use_operator=True),
                    (query_vector, query_vector),
                )
                return "\n".join(r["QUERY PLAN"] for r in cur.fetchall())
            finally:
                if ef_search is not None:
                    cur.execute("RESET hnsw.ef_search")


def serialize_latency_samples(samples: list[dict]) -> str:
    return json.dumps(samples)
