@dataclass
class Neighbour:
    row_id: int
    label: int
    distance: float


@dataclass
class RetrievalResult:
    neighbours: list[Neighbour]
    latency_ms: float
    used_index_scan: bool
    plan: str
    used_sequential_scan: bool = False
    applied_ef_search: int | None = None
    planner_mode: str = "natural"
    plan_checks: int = 0
    index_scan_checks: int = 0
    sequential_scan_checks: int = 0
    plan_check_plan: str = ""
    index_verification: dict[str, object] | None = None


def _distance_expr(metric: DistanceMetric, use_operator: bool) -> sql.Composable:
    """Distance expression for the metric.

    The *operator* form (``embedding <-> %s``) is what pgvector's HNSW index
    can satisfy; the *function* form (``l2_distance(...)``) always forces a
    full sequential scan and therefore serves as the exact baseline.
    """
    if use_operator:
        return sql.SQL("embedding {} %s").format(sql.SQL(metric.operator))
    return sql.SQL("{} (embedding, %s::vector)").format(sql.SQL(metric.function))


def _order_expr(dist: sql.Composable, use_operator: bool) -> sql.Composable:
    """Ordering for a nearest-neighbour query.

    The exhaustive path gets an ``id`` tiebreak so that a repeated exact query
    returns the same identifiers even when several rows share a distance.  The
    HNSW path keeps only the index-compatible distance ordering: adding a
    secondary sort key makes the planner abandon the index scan, which would
    turn an approximate measurement into a sequential scan.
    """
    if use_operator:
        return dist
    return sql.SQL("{dist}, id").format(dist=dist)


def _query_sql(
    dataset_id: int, metric: DistanceMetric, k: int, use_operator: bool
) -> sql.Composed:
    dist = _distance_expr(metric, use_operator)
    order = _order_expr(dist, use_operator)
    return sql.SQL(
        "SELECT id, label, {dist} AS distance "
        "FROM {t} "
        "ORDER BY {order} "
        "LIMIT {k}"
    ).format(
        dist=dist,
        order=order,
        t=sql.Identifier(train_table(dataset_id)),
        k=sql.Literal(k),
    )


def _explain_sql(
    dataset_id: int,
    metric: DistanceMetric,
    k: int,
    use_operator: bool,
    detailed: bool = True,
) -> sql.Composed:
    dist = _distance_expr(metric, use_operator)
    order = _order_expr(dist, use_operator)
    prefix = (
        "EXPLAIN (ANALYZE, BUFFERS, FORMAT TEXT) "
        if detailed
        else "EXPLAIN (FORMAT TEXT) "
    )
    return sql.SQL(
        prefix
        + "SELECT id, label, {dist} AS distance "
        "FROM {t} "
        "ORDER BY {order} "
        "LIMIT {k}"
    ).format(
        dist=dist,
        order=order,
        t=sql.Identifier(train_table(dataset_id)),
        k=sql.Literal(k),
    )


def _read_ef_search(cur) -> int | None:
    """Read the GUC from this exact cursor, or None if it is not defined yet."""
    try:
        cur.execute("SHOW hnsw.ef_search")
    except UndefinedObject:
        return None
    row = cur.fetchone()
    return int(row["hnsw.ef_search"]) if row else None


def _set_ef_search(cur, ef_search: int, transaction_local: bool = False) -> int | None:
    """Apply ef_search on the executing connection and prove it took effect."""
    previous = _read_ef_search(cur)
    keyword = "SET LOCAL" if transaction_local else "SET"
    cur.execute(f"{keyword} hnsw.ef_search = {int(ef_search)}")
    applied = _read_ef_search(cur)
    if applied != int(ef_search):
        raise RuntimeError(
            f"hnsw.ef_search was not applied: requested {ef_search}, server reported {applied}"
        )
    return previous


def _restore_ef_search(cur, previous: int | None, transaction_local: bool = False) -> None:
    if transaction_local:
        # The surrounding explicit transaction is rolled back, so SET LOCAL
        # expires without any action here.
        return
    if previous is None:
        cur.execute("RESET hnsw.ef_search")
    else:
        cur.execute(f"SET hnsw.ef_search = {int(previous)}")


def _check_plan(
    cur,
    dataset_id: int,
    metric: DistanceMetric,
    k: int,
    use_operator: bool,
    vector: str,
    detailed: bool,
) -> tuple[str, bool, bool]:
    """Run EXPLAIN for the exact SQL shape just timed and classify its access path."""
    cur.execute(
        _explain_sql(dataset_id, metric, k, use_operator, detailed=detailed),
        (vector, vector),
    )
    plan = "\n".join(r["QUERY PLAN"] for r in cur.fetchall())
    return (
        plan,
        plan_uses_index_scan(plan, index_name(dataset_id)),
        plan_uses_sequential_scan(plan),
    )


def _retrieve_on_cursor(
    cur,
    query_vector: str,
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    *,
    method: str,
    ef_search: int | None,
    use_operator: bool,
    warmup: bool,
    verify_plan: bool,
    detailed_plan: bool,
    planner_mode: str,
    transaction_local_ef: bool,
) -> RetrievalResult:
    """Execute one timed query on an already borrowed connection."""
    use_op = method == "hnsw" and use_operator
    verification: dict[str, object] | None = None
    if method == "hnsw":
        if planner_mode not in PLANNER_MODES:
            raise ValueError(f"unknown planner mode: {planner_mode!r}")
        if ef_search is None:
            raise ValueError("ef_search is required for HNSW retrieval")
        verification = verify_hnsw_index(dataset_id, metric).as_dict()

    previous_ef: int | None = None
    applied_ef: int | None = None
    stmt = _query_sql(dataset_id, metric, k, use_op)
    params = (query_vector, query_vector)

    try:
        if ef_search is not None:
            previous_ef = _set_ef_search(
                cur, ef_search, transaction_local=transaction_local_ef
            )
            applied_ef = _read_ef_search(cur)

        if warmup:
            cur.execute(stmt, params)
            cur.fetchall()

        start = time.perf_counter()
        cur.execute(stmt, params)
        rows = cur.fetchall()
        elapsed_ms = (time.perf_counter() - start) * 1000

        detailed_text = ""
        check_plan_text = ""
        used_index = False
        used_seq_scan = False
        checks = 0
        index_checks = 0
        seq_checks = 0

        if verify_plan:
            if detailed_plan:
                detailed_text, used_index, used_seq_scan = _check_plan(
                    cur, dataset_id, metric, k, use_op, query_vector, detailed=True
                )
                checks = 1
                index_checks = 1 if used_index else 0
                seq_checks = 1 if used_seq_scan else 0
            if method == "hnsw":
                # A cheap EXPLAIN (no ANALYZE) after the timer stops confirms
                # that this individual timed query used the verified index,
                # without executing the query again or warming buffers.
                check_plan_text, per_query_index, per_query_seq = _check_plan(
                    cur, dataset_id, metric, k, use_op, query_vector, detailed=False
                )
                checks += 1
                index_checks += 1 if per_query_index else 0
                seq_checks += 1 if per_query_seq else 0
                if detailed_plan:
                    used_index = used_index and per_query_index
                    used_seq_scan = used_seq_scan or per_query_seq
                else:
                    used_index = per_query_index
                    used_seq_scan = per_query_seq
    finally:
        if ef_search is not None:
            _restore_ef_search(
                cur, previous_ef, transaction_local=transaction_local_ef
            )

    neighbours = [
        Neighbour(
            row_id=int(r["id"]),
            label=int(r["label"]),
            distance=float(r["distance"]),
        )
        for r in rows
    ]
    return RetrievalResult(
        neighbours=neighbours,
        latency_ms=elapsed_ms,
        used_index_scan=used_index,
        plan=detailed_text,
        used_sequential_scan=used_seq_scan,
        applied_ef_search=applied_ef,
        planner_mode=planner_mode,
        plan_checks=checks,
        index_scan_checks=index_checks,
        sequential_scan_checks=seq_checks,
        plan_check_plan=check_plan_text,
        index_verification=verification,
    )


def retrieve(
    query_vector: str,
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    method: str = "exact",
    ef_search: int | None = None,
    use_operator: bool = True,
    warmup: bool = True,
    verify_plan: bool = True,
    planner_mode: str = "natural",
) -> RetrievalResult:
    """Run a single nearest-neighbour query and time it.

    ``method='exact'`` uses the distance *function* form, which can never be
    satisfied by an index and therefore guarantees an exhaustive scan.
    ``method='hnsw'`` uses the *operator* form so the planner can choose an
    HNSW index scan.

    Natural planner mode is the default and never forces an access path.
    Controlled HNSW mode is opt-in; callers using it must wrap the whole batch
    in an explicit transaction so that planner settings are transaction-local.
    For a direct single query, ``SET LOCAL`` still requires a transaction, so
    this helper uses the session-level form and restores the previous value.
    """
    if planner_mode not in PLANNER_MODES:
        raise ValueError(f"unknown planner mode: {planner_mode!r}")
    if method == "hnsw":
        # Invalid HNSW runs must never be silently accepted.
        verify_plan = True
    with connection() as conn:
        with conn.cursor() as cur:
            return _retrieve_on_cursor(
                cur,
                query_vector,
                k,
                metric,
                dataset_id,
                method=method,
                ef_search=ef_search,
                use_operator=use_operator,
                warmup=warmup,
                verify_plan=verify_plan,
                detailed_plan=True,
                planner_mode=planner_mode,
                transaction_local_ef=False,
            )


@dataclass
class BatchResult:
    """The outcome of a repeated timed query sweep.

    ``repetition_results[r]`` holds one :class:`RetrievalResult` per query
    for repetition ``r``, in the same query order every time. Keeping every
    repetition's neighbour sets — rather than only the last one — is what
    allows classification metrics to be computed *per repetition* instead of
    being inferred from a single aggregate.

    ``repetition_latencies[r]`` holds the measured latency of each query in
    that repetition. The warm-up query runs before the first measurement and
    is never stored, so ``sample_count == repetitions * unique_query_count``
    exactly.
    """

    repetition_results: list[list[RetrievalResult]]
    repetition_latencies: list[list[float]]
    repetitions: int
    warmup_queries: int
    plan: str = ""
    used_index_scan: bool = False
    used_sequential_scan: bool = False
    applied_ef_search: int | None = None
    planner_mode: str = "natural"
    plan_checks: int = 0
    index_scan_checks: int = 0
    sequential_scan_checks: int = 0
    plan_check_plan: str = ""
    index_verification: dict[str, object] | None = None
    planner_settings: dict[str, str] = field(default_factory=dict)

    @property
    def results(self) -> list[RetrievalResult]:
        """Neighbour sets from the final repetition."""
        return self.repetition_results[-1]

    @property
    def latencies(self) -> list[float]:
        """Every measured latency sample, flattened across repetitions."""
        return [ms for batch in self.repetition_latencies for ms in batch]

    @property
    def unique_query_count(self) -> int:
        return len(self.repetition_results[0]) if self.repetition_results else 0

    @property
    def sample_count(self) -> int:
        return sum(len(batch) for batch in self.repetition_latencies)


def retrieve_batch(
    query_vectors: Sequence[str],
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    method: str = "exact",
    ef_search: int | None = None,
    repetitions: int = 1,
    verify_plan: bool = True,
    planner_mode: str = "natural",
) -> BatchResult:
    """Run the query set ``repetitions`` times over the same vectors.

    Natural planner mode (default) leaves plan choice to PostgreSQL and keeps
    the original per-query connection behavior. Controlled HNSW mode is
    opt-in: it borrows one connection, opens an explicit transaction, issues
    ``SET LOCAL enable_seqscan = off`` and rolls the transaction back at the
    end. The two modes are mutually exclusive and are never pooled together.

    HNSW plan verification is mandatory. A detailed ``EXPLAIN (ANALYZE,
    BUFFERS)`` is captured for the first query as a diagnostic, and a cheap
    ``EXPLAIN`` is captured after *every* timed HNSW query to confirm that the
    plan belongs to that query without re-executing it.
    """
    if repetitions < 1:
        raise ValueError(f"repetitions must be at least 1 (got {repetitions})")
    if planner_mode not in PLANNER_MODES:
        raise ValueError(f"unknown planner mode: {planner_mode!r}")
    if planner_mode == "controlled_hnsw" and method != "hnsw":
        raise ValueError("controlled_hnsw planner mode requires method='hnsw'")
    if method == "hnsw":
        verify_plan = True

    repetition_results: list[list[RetrievalResult]] = []
    repetition_latencies: list[list[float]] = []
    plan = ""
    plan_check_plan = ""
    used_index = False
    used_seq = False
    applied_ef: int | None = None
    index_verification: dict[str, object] | None = None
    planner_settings: dict[str, str] = {}
    plan_checks = 0
    index_scan_checks = 0
    sequential_scan_checks = 0

    def accumulate(result: RetrievalResult, first: bool) -> None:
        nonlocal plan, plan_check_plan, used_index, used_seq, applied_ef
        nonlocal index_verification, plan_checks, index_scan_checks, sequential_scan_checks
        if first:
            plan = result.plan
            plan_check_plan = result.plan_check_plan
            used_index = result.used_index_scan
            used_seq = result.used_sequential_scan
            applied_ef = result.applied_ef_search
            index_verification = result.index_verification
        else:
            used_index = used_index and result.used_index_scan
            used_seq = used_seq or result.used_sequential_scan
        plan_checks += result.plan_checks
        index_scan_checks += result.index_scan_checks
        sequential_scan_checks += result.sequential_scan_checks

    def snapshot(cur) -> dict[str, str]:
        cur.execute("SHOW enable_seqscan")
        snapshot_value = {
            "enable_seqscan": str(cur.fetchone()["enable_seqscan"]),
            "hnsw.ef_search": str(_read_ef_search(cur)),
        }
        return snapshot_value

    if planner_mode == "controlled_hnsw":
        with connection() as conn:
            with conn.cursor() as cur:
                cur.execute("BEGIN")
                try:
                    cur.execute("SET LOCAL enable_seqscan = off")
                    for repetition in range(repetitions):
                        current: list[RetrievalResult] = []
                        latencies: list[float] = []
                        for i, vec in enumerate(query_vectors):
                            first = repetition == 0 and i == 0
                            result = _retrieve_on_cursor(
                                cur,
                                vec,
                                k,
                                metric,
                                dataset_id,
                                method=method,
                                ef_search=ef_search,
                                use_operator=True,
                                warmup=first,
                                verify_plan=verify_plan,
                                detailed_plan=first,
                                planner_mode=planner_mode,
                                transaction_local_ef=True,
                            )
                            current.append(result)
                            latencies.append(result.latency_ms)
                            if first:
                                planner_settings = snapshot(cur)
                            accumulate(result, first)
                        repetition_results.append(current)
                        repetition_latencies.append(latencies)
                except Exception:
                    cur.execute("ROLLBACK")
                    raise
                cur.execute("ROLLBACK")
    else:
        for repetition in range(repetitions):
            current = []
            latencies = []
            for i, vec in enumerate(query_vectors):
                first = repetition == 0 and i == 0
                with connection() as conn:
                    with conn.cursor() as cur:
                        result = _retrieve_on_cursor(
                            cur,
                            vec,
                            k,
                            metric,
                            dataset_id,
                            method=method,
                            ef_search=ef_search,
                            use_operator=True,
                            warmup=first,
                            verify_plan=(
                                verify_plan if method == "hnsw" else (verify_plan and first)
                            ),
                            detailed_plan=first,
                            planner_mode=planner_mode,
                            transaction_local_ef=False,
                        )
                        if first:
                            planner_settings = snapshot(cur)
                current.append(result)
                latencies.append(result.latency_ms)
                accumulate(result, first)
            repetition_results.append(current)
            repetition_latencies.append(latencies)

    return BatchResult(
        repetition_results=repetition_results,
        repetition_latencies=repetition_latencies,
        repetitions=repetitions,
        warmup_queries=1 if query_vectors else 0,
        plan=plan,
        used_index_scan=used_index,
        used_sequential_scan=used_seq,
        applied_ef_search=applied_ef,
        planner_mode=planner_mode,
        plan_checks=plan_checks,
        index_scan_checks=index_scan_checks,
        sequential_scan_checks=sequential_scan_checks,
        plan_check_plan=plan_check_plan,
        index_verification=index_verification,
        planner_settings=planner_settings,
    )


@dataclass
class TieTolerance:
    """Floating-point tolerance for "equally distant" in tie-aware recall.

    Two rows are treated as equally valid neighbours when

    ``distance <= boundary * (1 + relative) + absolute``

    where ``boundary`` is the exact K-th neighbour distance. An exact tie
    between duplicate feature vectors produces bit-identical distance values,
    so the tolerance only has to absorb float4/float8 representation error;
    it must be far smaller than the spacing between genuinely distinct
    distances.
    """

    relative: float = 1e-6
    absolute: float = 1e-6


@dataclass
class GroundTruth:
    """Exact neighbours plus the tie-tolerant candidate set for one query."""

    ids: list[int]
    distances: list[float]
    boundary: float
    candidate_ids: list[int]
    candidate_labels: dict[int, int]

    @property
    def is_tied(self) -> bool:
        return len(self.candidate_ids) > len(self.ids)


def _ground_truth_sql(
    dataset_id: int, metric: DistanceMetric, k: int
) -> sql.Composed:
    """Exhaustive top-k plus every row tied at the K-th distance.

    ``ORDER BY distance, id`` makes the conventional reference deterministic:
    without the id tiebreak the K-th boundary row is chosen arbitrarily by
    the executor, which would make conventional Recall@K irreproducible.
    """
    dist = _distance_expr(metric, use_operator=False)
    return sql.SQL(
        "WITH scored AS ("
        "  SELECT id, label, {dist} AS distance FROM {t}"
        "), boundary AS ("
        "  SELECT COALESCE("
        "    (SELECT distance FROM scored ORDER BY distance LIMIT 1 OFFSET {off}),"
        "    (SELECT max(distance) FROM scored)"
        "  ) AS b"
        ")"
        " SELECT id, label, distance FROM scored"
        " WHERE distance <= (SELECT b FROM boundary) * (1 + %s) + %s"
        " ORDER BY distance, id"
    ).format(dist=dist, t=sql.Identifier(train_table(dataset_id)), off=sql.Literal(k - 1))


def ground_truth_candidates(
    query_vectors: Sequence[str],
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    tolerance: TieTolerance | None = None,
) -> list[GroundTruth]:
    """Reference neighbour set for every query, tie-tolerant.

    Returns one :class:`GroundTruth` per query containing the exact top-k
    ids/distances (deterministic by ``(distance, id)``), the K-th boundary
    distance, and every training id within the tie tolerance of that
    boundary.
    """
    tol = tolerance or TieTolerance()
    stmt = _ground_truth_sql(dataset_id, metric, k)
    out: list[GroundTruth] = []

    with connection() as conn:
        with conn.cursor() as cur:
            for vec in query_vectors:
                cur.execute(stmt, (vec, tol.relative, tol.absolute))
                rows = cur.fetchall()
                ids = [int(r["id"]) for r in rows]
                distances = [float(r["distance"]) for r in rows]
                if not ids:
                    out.append(GroundTruth([], [], 0.0, [], {}))
                    continue
                boundary = distances[k - 1] if len(distances) >= k else distances[-1]
                out.append(
                    GroundTruth(
                        ids=ids[:k],
                        distances=distances[:k],
                        boundary=boundary,
                        candidate_ids=ids,
                        candidate_labels={
                            int(r["id"]): int(r["label"]) for r in rows
                        },
                    )
                )
    return out


def ground_truth_ids(
    query_vectors: Sequence[str],
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
) -> list[list[int]]:
    """Exact top-k neighbour ids, used as the conventional recall reference."""
    return [
        gt.ids
        for gt in ground_truth_candidates(query_vectors, k, metric, dataset_id)
    ]


def explain_plan(
    query_vector: str,
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    ef_search: int | None = None,
) -> str:
    """Return the EXPLAIN output for the retrieval query."""
    with connection() as conn:
        with conn.cursor() as cur:
            if ef_search is not None:
                cur.execute(f"SET hnsw.ef_search = {int(ef_search)}")
            try:
                cur.execute(
                    _explain_sql(dataset_id, metric, k, use_operator=True),
                    (query_vector, query_vector),
                )
                return "\n".join(r["QUERY PLAN"] for r in cur.fetchall())
            finally:
                if ef_search is not None:
                    cur.execute("RESET hnsw.ef_search")


