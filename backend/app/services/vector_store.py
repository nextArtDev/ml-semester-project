"""Vector storage and retrieval against PostgreSQL + pgvector.

Two retrieval strategies are implemented:

``exact``
    A sequential scan over the training pool with the pgvector distance
    function applied to every candidate row. This is the ground truth used
    for recall computation and the accuracy baseline.

``hnsw``
    An index scan over a Hierarchical Navigable Small World index. The
    ``ef_search`` GUC controls the search-effort and directly drives the
    recall / latency trade-off studied in the project.

Both strategies share the same SQL shape so that the *only* difference
between a baseline run and an approximate run is the presence of the index
and the planner's choice of access path.

Each dataset owns a pair of tables (``fv_<id>`` / ``tv_<id>``) with a
dimensionally-typed ``vector(dim)`` column, which is what pgvector requires
for a usable HNSW index.
"""

from __future__ import annotations

import json
import logging
import time
from dataclasses import dataclass
from typing import Sequence

from psycopg import sql

from app.core.database import connection
from app.services.metrics import DistanceMetric

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Table naming
# ---------------------------------------------------------------------------
def train_table(dataset_id: int) -> str:
    return f"fv_{int(dataset_id)}"


def test_table(dataset_id: int) -> str:
    return f"tv_{int(dataset_id)}"


def index_name(dataset_id: int) -> str:
    return f"fv_{int(dataset_id)}_embedding_hnsw_idx"


# ---------------------------------------------------------------------------
# Table lifecycle
# ---------------------------------------------------------------------------
def create_dataset_tables(dataset_id: int, dimension: int) -> None:
    """Create the train/test tables for a dataset with a typed vector column."""
    dim = int(dimension)
    with connection() as conn:
        with conn.cursor() as cur:
            for table in (train_table(dataset_id), test_table(dataset_id)):
                cur.execute(sql.SQL("DROP TABLE IF EXISTS {t} CASCADE").format(
                    t=sql.Identifier(table)
                ))
                cur.execute(
                    sql.SQL(
                        "CREATE TABLE {t} ("
                        "  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                        "  row_index   INTEGER NOT NULL,"
                        "  label       SMALLINT NOT NULL,"
                        "  embedding   vector({dim}) NOT NULL"
                        ")"
                    ).format(t=sql.Identifier(table), dim=sql.Literal(dim))
                )
                cur.execute(
                    sql.SQL("CREATE INDEX {i} ON {t} (row_index)").format(
                        i=sql.Identifier(f"{table}_row_idx"), t=sql.Identifier(table)
                    )
                )
    logger.info("Created vector tables for dataset %s (dim=%s)", dataset_id, dim)


def drop_dataset_tables(dataset_id: int) -> None:
    with connection() as conn:
        with conn.cursor() as cur:
            for table in (train_table(dataset_id), test_table(dataset_id)):
                cur.execute(sql.SQL("DROP TABLE IF EXISTS {t} CASCADE").format(
                    t=sql.Identifier(table)
                ))


# ---------------------------------------------------------------------------
# Ingestion
# ---------------------------------------------------------------------------
def insert_vectors(
    dataset_id: int,
    which: str,
    embeddings: Sequence[str],
    labels: Sequence[int],
    row_indices: Sequence[int],
) -> int:
    """Bulk insert feature vectors using COPY for throughput."""
    table = train_table(dataset_id) if which == "train" else test_table(dataset_id)

    with connection() as conn:
        with conn.cursor() as cur:
            with cur.copy(
                sql.SQL(
                    "COPY {table} (row_index, label, embedding) FROM STDIN"
                ).format(table=sql.Identifier(table))
            ) as copy:
                for emb, lab, idx in zip(embeddings, labels, row_indices):
                    copy.write_row((int(idx), int(lab), emb))
    logger.info("Inserted %s rows into %s", len(labels), table)
    return len(labels)


def count_vectors(dataset_id: int, which: str = "train") -> int:
    table = train_table(dataset_id) if which == "train" else test_table(dataset_id)
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                sql.SQL("SELECT count(*) AS c FROM {t}").format(t=sql.Identifier(table))
            )
            row = cur.fetchone()
            return int(row["c"]) if row else 0


def load_test_vectors(dataset_id: int, limit: int | None) -> list[tuple[int, int, str]]:
    """Return ``(id, label, embedding_text)`` triples for the query pool."""
    table = test_table(dataset_id)
    limit_clause = sql.SQL(" LIMIT {n}").format(n=sql.Literal(limit)) if limit else sql.SQL("")
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                sql.SQL(
                    "SELECT id, label, embedding::text AS embedding FROM {t} ORDER BY id{l}"
                ).format(t=sql.Identifier(table), l=limit_clause)
            )
            return [(int(r["id"]), int(r["label"]), r["embedding"]) for r in cur.fetchall()]


# ---------------------------------------------------------------------------
# Index management
# ---------------------------------------------------------------------------
def drop_hnsw_index(dataset_id: int) -> None:
    """Remove the HNSW index for a dataset (used before exact-only runs)."""
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("DROP INDEX IF EXISTS {i}").format(
                i=sql.Identifier(index_name(dataset_id))
            ))


def create_hnsw_index(
    dataset_id: int,
    metric: DistanceMetric,
    m: int = 16,
    ef_construction: int = 64,
    force: bool = False,
) -> float:
    """Build the HNSW index and return the build time in milliseconds.

    If an index with the same parameters already exists it is reused, which
    keeps an ``ef_search`` sweep cheap. Pass ``force=True`` to rebuild.
    """
    existing = get_hnsw_index(dataset_id)
    if (
        not force
        and existing is not None
        and existing["distance_metric"] == metric.value
        and int(existing["m"]) == int(m)
        and int(existing["ef_construction"]) == int(ef_construction)
    ):
        logger.info("Reusing existing HNSW index for dataset %s", dataset_id)
        return float(existing["build_ms"] or 0.0)

    ops = {
        DistanceMetric.L2: "vector_l2_ops",
        DistanceMetric.COSINE: "vector_cosine_ops",
        DistanceMetric.L1: "vector_l1_ops",
    }[metric]

    drop_hnsw_index(dataset_id)
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute("SET maintenance_work_mem = '512MB'")
            start = time.perf_counter()
            cur.execute(
                sql.SQL(
                    "CREATE INDEX {idx} ON {t} USING hnsw (embedding {ops}) "
                    "WITH (m = {m}, ef_construction = {efc})"
                ).format(
                    idx=sql.Identifier(index_name(dataset_id)),
                    t=sql.Identifier(train_table(dataset_id)),
                    ops=sql.SQL(ops),
                    m=sql.Literal(m),
                    efc=sql.Literal(ef_construction),
                )
            )
            elapsed = (time.perf_counter() - start) * 1000
            cur.execute(
                sql.SQL(
                    "INSERT INTO hnsw_indexes "
                    "(dataset_id, distance_metric, m, ef_construction, build_ms, built_at) "
                    "VALUES (%s, %s, %s, %s, %s, now()) "
                    "ON CONFLICT (dataset_id) DO UPDATE SET "
                    "distance_metric = EXCLUDED.distance_metric, "
                    "m = EXCLUDED.m, "
                    "ef_construction = EXCLUDED.ef_construction, "
                    "build_ms = EXCLUDED.build_ms, "
                    "built_at = now()"
                ),
                (dataset_id, metric.value, int(m), int(ef_construction), elapsed),
            )
    logger.info("HNSW index built in %.1f ms (m=%s, ef_construction=%s)", elapsed, m, ef_construction)
    return elapsed


def get_hnsw_index(dataset_id: int) -> dict | None:
    """Return the recorded HNSW index parameters for a dataset, if any."""
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT * FROM hnsw_indexes WHERE dataset_id = %s", (dataset_id,)
            )
            return cur.fetchone()


def hnsw_index_exists(dataset_id: int) -> bool:
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT 1 AS present FROM pg_indexes "
                "WHERE tablename = %s AND indexname = %s",
                (train_table(dataset_id), index_name(dataset_id)),
            )
            return cur.fetchone() is not None


def analyze(dataset_id: int) -> None:
    """Refresh planner statistics so it can pick the right access path."""
    with connection() as conn:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("ANALYZE {t}").format(t=sql.Identifier(train_table(dataset_id))))
            cur.execute(sql.SQL("ANALYZE {t}").format(t=sql.Identifier(test_table(dataset_id))))


def plan_uses_index_scan(plan_text: str) -> bool:
    """Detect whether the planner chose an HNSW index scan."""
    lowered = plan_text.lower()
    return "index scan" in lowered and ("hnsw" in lowered or "index searches" in lowered)


# ---------------------------------------------------------------------------
# Retrieval
# ---------------------------------------------------------------------------
@dataclass
class Neighbour:
    row_id: int
    label: int
    distance: float


@dataclass
class RetrievalResult:
    neighbours: list[Neighbour]
    latency_ms: float
    used_index_scan: bool
    plan: str


def _distance_expr(metric: DistanceMetric, use_operator: bool) -> sql.Composable:
    """Distance expression for the metric.

    The *operator* form (``embedding <-> %s``) is what pgvector's HNSW index
    can satisfy; the *function* form (``l2_distance(...)``) always forces a
    full sequential scan and therefore serves as the exact baseline.
    """
    if use_operator:
        return sql.SQL("embedding {} %s").format(sql.SQL(metric.operator))
    return sql.SQL("{} (embedding, %s::vector)").format(sql.SQL(metric.function))


def _query_sql(
    dataset_id: int, metric: DistanceMetric, k: int, use_operator: bool
) -> sql.Composed:
    dist = _distance_expr(metric, use_operator)
    return sql.SQL(
        "SELECT id, label, {dist} AS distance "
        "FROM {t} "
        "ORDER BY {dist} "
        "LIMIT {k}"
    ).format(dist=dist, t=sql.Identifier(train_table(dataset_id)), k=sql.Literal(k))


def _explain_sql(
    dataset_id: int, metric: DistanceMetric, k: int, use_operator: bool
) -> sql.Composed:
    dist = _distance_expr(metric, use_operator)
    return sql.SQL(
        "EXPLAIN (ANALYZE, FORMAT TEXT) "
        "SELECT id, label, {dist} AS distance "
        "FROM {t} "
        "ORDER BY {dist} "
        "LIMIT {k}"
    ).format(dist=dist, t=sql.Identifier(train_table(dataset_id)), k=sql.Literal(k))


def retrieve(
    query_vector: str,
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    method: str = "exact",
    ef_search: int | None = None,
    use_operator: bool = True,
    warmup: bool = True,
) -> RetrievalResult:
    """Run a single nearest-neighbour query and time it.

    ``method='exact'`` uses the distance *function* form, which can never be
    satisfied by an index and therefore guarantees an exhaustive scan.
    ``method='hnsw'`` uses the *operator* form so the planner can choose an
    HNSW index scan.
    """
    use_op = method == "hnsw" and use_operator

    with connection() as conn:
        with conn.cursor() as cur:
            # The pool runs in autocommit mode, where SET LOCAL is a no-op,
            # so the search-effort parameter is set at session level and
            # explicitly restored afterwards.
            if ef_search is not None:
                cur.execute(f"SET hnsw.ef_search = {int(ef_search)}")
            try:
                stmt = _query_sql(dataset_id, metric, k, use_op)
                params: tuple = (query_vector, query_vector)

                # Warm-up run so that the measured latency is not dominated by
                # first-call planning and buffer-cache population.
                if warmup:
                    cur.execute(stmt, params)
                    cur.fetchall()

                start = time.perf_counter()
                cur.execute(stmt, params)
                rows = cur.fetchall()
                elapsed_ms = (time.perf_counter() - start) * 1000

                plan = ""
                used_index = False
                if method == "hnsw":
                    cur.execute(_explain_sql(dataset_id, metric, k, use_op), params)
                    plan = "\n".join(r["QUERY PLAN"] for r in cur.fetchall())
                    used_index = plan_uses_index_scan(plan)
            finally:
                if ef_search is not None:
                    cur.execute("RESET hnsw.ef_search")

    neighbours = [
        Neighbour(
            row_id=int(r["id"]),
            label=int(r["label"]),
            distance=float(r["distance"]),
        )
        for r in rows
    ]
    return RetrievalResult(
        neighbours=neighbours,
        latency_ms=elapsed_ms,
        used_index_scan=used_index,
        plan=plan,
    )


def retrieve_batch(
    query_vectors: Sequence[str],
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    method: str = "exact",
    ef_search: int | None = None,
) -> list[RetrievalResult]:
    """Run one query per vector and return the per-query results."""
    results: list[RetrievalResult] = []
    for i, vec in enumerate(query_vectors):
        results.append(
            retrieve(
                query_vector=vec,
                k=k,
                metric=metric,
                dataset_id=dataset_id,
                method=method,
                ef_search=ef_search,
                warmup=(i == 0),
            )
        )
    return results


def ground_truth_ids(
    query_vectors: Sequence[str],
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
) -> list[list[int]]:
    """Exact top-k neighbour ids, used as the recall reference."""
    out: list[list[int]] = []
    stmt = _query_sql(dataset_id, metric, k, use_operator=False)
    with connection() as conn:
        with conn.cursor() as cur:
            for vec in query_vectors:
                cur.execute(stmt, (vec, vec))
                out.append([int(r["id"]) for r in cur.fetchall()])
    return out


def explain_plan(
    query_vector: str,
    k: int,
    metric: DistanceMetric,
    dataset_id: int,
    ef_search: int | None = None,
) -> str:
    """Return the EXPLAIN output for the retrieval query."""
    with connection() as conn:
        with conn.cursor() as cur:
            if ef_search is not None:
                cur.execute(f"SET hnsw.ef_search = {int(ef_search)}")
            try:
                cur.execute(
                    _explain_sql(dataset_id, metric, k, use_operator=True),
                    (query_vector, query_vector),
                )
                return "\n".join(r["QUERY PLAN"] for r in cur.fetchall())
            finally:
                if ef_search is not None:
                    cur.execute("RESET hnsw.ef_search")


def serialize_latency_samples(samples: list[dict]) -> str:
    return json.dumps(samples)
